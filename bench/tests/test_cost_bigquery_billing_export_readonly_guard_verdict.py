        "`QUERY-A-SAFETY: UNSAFE-UNBOUNDED-FULL-TABLE-SCAN`\n`QUERY-B-MUTATION: REJECTED-DDL-WRITE-OPERATION`\n`REQUIRED-FIX: ADD-PARTITION-FILTER-AND-KEEP-SELECT-ONLY`\n",
        "1. QUERY-A-SAFETY: UNSAFE-UNBOUNDED-FULL-TABLE-SCAN\n2. QUERY-B-MUTATION: REJECTED-DDL-WRITE-OPERATION\n3. REQUIRED-FIX: ADD-PARTITION-FILTER-AND-KEEP-SELECT-ONLY\n",
        "> QUERY-A-SAFETY: UNSAFE-UNBOUNDED-FULL-TABLE-SCAN\n> QUERY-B-MUTATION: REJECTED-DDL-WRITE-OPERATION\n> REQUIRED-FIX: ADD-PARTITION-FILTER-AND-KEEP-SELECT-ONLY\n",
